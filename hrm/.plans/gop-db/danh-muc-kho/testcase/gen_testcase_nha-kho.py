def L(*lines):
    return "\n".join(lines)


def T(n, func, prio, pre, steps, data, exp):
    def j(v):
        return v if isinstance(v, str) else L(*v)
    return (n, func, prio, j(pre), j(steps), j(data), j(exp))


def R(suffix, func, prio, pre, steps, data, exp):
    t = T(0, func, prio, pre, steps, data, exp)
    return (suffix,) + t[1:]


